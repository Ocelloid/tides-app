const NONBINARY_GENDER_IDS = new Set(["gender-nonbinary", "gender-agender"]);

function pickRandom<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)]!;
}

function poolById(poolId: string): RaceNamePool | undefined {
  return raceNamePools[poolId];
}

function fallbackPoolIds(): string[] {
  return Object.keys(raceNamePools);
}

function namesForGender(pool: RaceNamePool, genderId: string): string[] {
  if (NONBINARY_GENDER_IDS.has(genderId)) {
    return [...pool.male, ...pool.female];
  }
  if (genderId === "gender-woman") {
    return pool.female.length > 0 ? pool.female : pool.male;
  }
  return pool.male.length > 0 ? pool.male : pool.female;
}

function resolvePool(raceId: string): RaceNamePool | undefined {
  const poolId = raceToNamePoolId[raceId];
  if (poolId) {
    return poolById(poolId);
  }
  return undefined;
}

function fallbackNames(genderId: string): string {
  const poolIds = fallbackPoolIds();
  const poolId = pickRandom(poolIds);
  const pool = poolById(poolId)!;
  return pickRandom(namesForGender(pool, genderId));
}

/** Случайное имя для расы и пола из хроники. */
export function rollRaceName(raceId: string, genderId: string): string {
  const pool = resolvePool(raceId);
  if (!pool) {
    return fallbackNames(genderId);
  }
  const names = namesForGender(pool, genderId);
  if (names.length === 0) {
    return fallbackNames(genderId);
  }
  return pickRandom(names);
}

